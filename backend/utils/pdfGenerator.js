/**
 * pdfGenerator.js
 * Generates professional PDFs for freight documents:
 *  - Bill of Lading (BOL)
 *  - Rate Confirmation
 */

const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

const UPLOADS_DIR = path.join(__dirname, '../public/documents/uploads');
if (!fs.existsSync(UPLOADS_DIR)) fs.mkdirSync(UPLOADS_DIR, { recursive: true });

// ── Shared helpers ──────────────────────────────────────────────────────────

function drawHRule(doc, y, color) {
  doc.moveTo(50, y).lineTo(562, y).strokeColor(color || '#334155').lineWidth(0.5).stroke();
}

function fmtDate(d) {
  if (!d) return 'N/A';
  return new Date(d).toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' });
}

// Carrier identity for documents — same rule as pickupVerificationService.carrierIdentity:
// a verified carrier's FMCSA-record values are printed; anything else is the typed
// profile value, labelled. A missing confirmed number never silently falls back to a typed one.
function carrierDocIdentity(c) {
  const v = (c && c.verification) || {};
  const f = (v.status === 'verified' && v.fmcsaData) || {};
  const pick = (confirmed, typed) =>
    confirmed ? String(confirmed) : (typed ? `${typed} (self-reported)` : 'N/A');
  return {
    name: pick(f.legalName, c && (c.companyName || c.name)),
    mcNumber: pick(f.mcNumber, c && c.mcNumber),
    dotNumber: pick(f.dotNumber, c && c.dotNumber),
  };
}
exports.carrierDocIdentity = carrierDocIdentity;

function fmtMoney(n) {
  return '$' + Number(n || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function addHeader(doc, title, subtitle) {
  doc.rect(0, 0, 612, 90).fill('#1e1040');
  doc.fontSize(22).fillColor('#ffffff').font('Helvetica-Bold')
    .text('FreightConnect', 50, 22);
  doc.fontSize(10).fillColor('#a78bfa').font('Helvetica')
    .text('www.freightconnect.io', 50, 48);
  doc.fontSize(18).fillColor('#ffffff').font('Helvetica-Bold')
    .text(title, 300, 22, { align: 'right', width: 262 });
  if (subtitle) {
    doc.fontSize(10).fillColor('#a78bfa').font('Helvetica')
      .text(subtitle, 300, 48, { align: 'right', width: 262 });
  }
  doc.fillColor('#000000');
}

function addFooter(doc) {
  const y = doc.page.height - 50;
  doc.page.margins.bottom = 0; // the footer sits inside the bottom margin; without this PDFKit starts a blank page for it
  drawHRule(doc, y - 10, '#e2e8f0');
  doc.fontSize(9).fillColor('#64748b').font('Helvetica')
    .text(
      'Generated by FreightConnect · ' + new Date().toLocaleDateString(),
      50, y, { align: 'center', width: 512 }
    );
}

function sectionTitle(doc, text, y) {
  if (y > doc.page.height - 130) { doc.addPage(); y = 60; }
  doc.rect(50, y, 512, 20).fill('#f1f5f9');
  doc.fontSize(10).fillColor('#1e1040').font('Helvetica-Bold')
    .text(text, 56, y + 5);
  doc.font('Helvetica').fillColor('#000000');
  return y + 28;
}

function infoRow(doc, label, value, y) {
  if (y > doc.page.height - 90) { doc.addPage(); y = 60; }
  // The built-in PDF fonts are Latin-1 only: an arrow in a load title printed as garbage.
  const v = String(value != null ? value : 'N/A').replace(/\s*[→➔➡]\s*/g, ' to ').replace(/[^\x00-\xFF]/g, '?');
  doc.fontSize(9.5).fillColor('#64748b').font('Helvetica')
    .text(label, 50, y, { width: 180 });
  doc.fontSize(9.5).fillColor('#1e293b').font('Helvetica-Bold')
    .text(v, 240, y, { width: 322 });
  return y + Math.max(17, Math.ceil(doc.heightOfString(v, { width: 322 })) + 5); // long values (addresses, instructions) wrap
}

function sigLine(doc, label, x, y, lineWidth) {
  doc.fontSize(9).fillColor('#1e293b').font('Helvetica').text(label, x, y + 4);
  doc.moveTo(x + 110, y + 18).lineTo(lineWidth, y + 18) // lineWidth is the right edge of the column
    .strokeColor('#94a3b8').lineWidth(0.8).stroke();
}

// Render a captured e-signature (base64 PNG data URL) into a signature column,
// or fall back to a blank ruled line when none was captured. A corrupt/oversized
// PNG must never crash BOL generation — hence the try/catch.
function drawSignature(doc, sig, label, x, y, lineWidth) {
  const dataUrl = sig && sig.dataUrl;
  if (dataUrl && /^data:image\/png;base64,/.test(dataUrl)) {
    try {
      const b64 = dataUrl.replace(/^data:image\/png;base64,/, '');
      doc.image(Buffer.from(b64, 'base64'), x + 114, y - 20, { fit: [lineWidth - x - 118, 36] }); // sits on the signature line
    } catch (_) { /* fall through to the ruled line below */ }
  }
  sigLine(doc, label, x, y, lineWidth);
  sigLine(doc, 'Print Name:', x, y + 28, lineWidth);
  if (sig && sig.signerName) {
    doc.fontSize(9).fillColor('#1e293b').font('Helvetica').text(String(sig.signerName), x + 112, y + 32);
  }
  sigLine(doc, 'Date:', x, y + 56, lineWidth);
  if (sig && sig.signedAt) {
    doc.fontSize(9).fillColor('#1e293b').font('Helvetica').text(fmtDateTime(sig.signedAt), x + 112, y + 60);
  }
}

// ── What the documents say (pure, so it can be tested without reading a PDF) ──

function fmtDateTime(d) {
  if (!d) return null;
  return new Date(d).toLocaleString('en-US', { dateStyle: 'medium', timeStyle: 'short', timeZone: 'UTC' }) + ' UTC';
}
function fmtWindow(w) {
  const a = fmtDateTime(w && w.start), b = fmtDateTime(w && w.end);
  if (a && b) return a + '  to  ' + b;
  return a || b || 'Not set';
}
const joinParts = (...parts) => parts.filter(Boolean).join(' · ');

/** The hazmat basic description in the order a shipping paper carries it: ID number, proper shipping name, class, packing group. */
function hazmatDescription(load) {
  if (!load.hazardousMaterial) return null;
  return [
    load.dangerousGoodsUN,
    load.hazmatShippingName,
    load.hazmatClass && ('Class ' + String(load.hazmatClass).replace(/^class\s*/i, '')),
    load.hazmatPackingGroup && ('PG ' + String(load.hazmatPackingGroup).replace(/^pg\s*/i, '')),
  ].filter(Boolean).join(', ') || 'YES (details not provided by the shipper)';
}

/** The two signatures taken at pickup. Older loads stored a shipper's signature in the single pickup slot. */
function pickupSignatures(load) {
  const ps = load.pickupSignature || {};
  const own = load.shipperSignature && load.shipperSignature.dataUrl ? load.shipperSignature : null;
  return {
    shipper: own || (ps.signedByRole === 'shipper' ? ps : null),
    driver: ps.signedByRole === 'shipper' ? null : ps,
  };
}

/** Pickup or delivery place as label/value rows; rows with nothing to say are left out. */
function placeRows(load, side) {
  const p = side === 'pickup'
    ? { name: load.pickupFacilityName, addr: load.pickupAddress || load.origin, cn: load.pickupContactName, cp: load.pickupContactPhone, hours: load.pickupHours, win: load.pickupTimeWindow }
    : { name: load.deliveryFacilityName, addr: load.deliveryAddress || load.destination, cn: load.deliveryContactName, cp: load.deliveryContactPhone, hours: load.deliveryHours, win: load.deliveryTimeWindow };
  return [
    ['Facility', p.name],
    ['Address', p.addr],
    ['Contact', joinParts(p.cn, p.cp)],
    ['Facility hours', p.hours],
    [side === 'pickup' ? 'Pickup window' : 'Delivery window', fmtWindow(p.win)],
  ].filter((r) => r[1]);
}

function freightRows(load) {
  const d = load.loadDimensions;
  return [
    ['Description', load.title],
    ['Commodity', load.commodityType || 'General freight'],
    ['Pieces', load.pieceCount ? joinParts(String(load.pieceCount) + (load.packageType ? ' ' + load.packageType : '')) : null],
    ['Weight', load.loadWeight ? Number(load.loadWeight).toLocaleString('en-US') + ' lbs' : null],
    ['Dimensions', d && d.length ? d.length + 'L x ' + d.width + 'W x ' + d.height + 'H ft' : null],
    ['Equipment', joinParts(load.equipmentType, load.equipmentSubtype)],
  ].filter((r) => r[1]);
}

function referenceRows(load) {
  return [
    ['PO number', load.poNumber],
    ['Shipper reference', load.shipperReferenceNumber],
    ['Consignee reference', load.consigneeReference],
    ['Pickup number', load.pickupNumber],
  ].filter((r) => r[1]);
}

/** Every section of the bill of lading, in print order. The rate is never here: the receiver reads this document. */
function bolSections(load, carrier, shipper) {
  const id = carrierDocIdentity(carrier);
  const haz = hazmatDescription(load);
  const extraStops = (load.stops || []).slice().sort((a, b) => a.sequence - b.sequence)
    .map((s) => [(s.type === 'pickup' ? 'Pickup' : 'Delivery') + ' stop ' + s.sequence, joinParts(s.address, s.contactName, s.contactPhone)]);
  const sections = [
    { title: 'PARTIES', rows: [
      ['Shipper', (shipper && (shipper.companyName || shipper.name)) || 'N/A'],
      ['Carrier', id.name], ['MC number', id.mcNumber], ['DOT number', id.dotNumber],
      ['Driver', load.assignedDriverName], ['Truck / unit', load.assignedTruckId],
    ].filter((r) => r[1]) },
    { title: 'REFERENCE NUMBERS', rows: [['Bill of lading number', String(load._id)], ...referenceRows(load)] },
    { title: 'SHIP FROM', rows: placeRows(load, 'pickup') },
    { title: 'SHIP TO', rows: [...placeRows(load, 'delivery'), ['Delivered at', fmtDateTime(load.deliveredAt)]].filter((r) => r[1]) },
  ];
  if (extraStops.length) sections.push({ title: 'STOPS', rows: extraStops });
  sections.push({ title: 'FREIGHT', rows: [
    ...freightRows(load),
    ['Seal number', load.sealNumber],
    ['Special instructions', load.specialInstructions],
    ['Receiver notes', load.deliverySignature && load.deliverySignature.note],
  ].filter((r) => r[1]) });
  sections.push(haz
    ? { title: 'HAZARDOUS MATERIAL', rows: [['Shipping description', haz], ['24-hour emergency phone', load.hazmatEmergencyPhone || 'NOT PROVIDED']] }
    : { title: 'HAZARDOUS MATERIAL', rows: [['Hazardous material', 'No']] });
  return sections;
}

/**
 * The money and the terms on a rate confirmation: what this platform actually does, not a template.
 * opts: { feePct, paymentsOn, detention: { freeMinutes, rateCentsPerHour }, tonuCents }
 */
function rateConTerms(load, opts) {
  const o = opts || {};
  const rateCents = Math.round(Number(load.rate || 0) * 100);
  const feeCents = Math.round(rateCents * (o.feePct || 0));
  const det = o.detention || { freeMinutes: 120, rateCentsPerHour: 7500 };
  const freeHours = Math.round((det.freeMinutes / 60) * 100) / 100;
  const money = (c) => fmtMoney(c / 100);
  const rows = [
    ['Payment terms', load.paymentTerms || 'Not stated by the shipper'],
    ['How payment is made', o.paymentsOn
      ? 'Through FreightConnect: the shipper\'s payment is authorised at booking, charged when delivery is confirmed, then paid out to the carrier.'
      : 'Directly between shipper and carrier. FreightConnect is not holding or moving funds for this load.'],
  ];
  if (o.paymentsOn) {
    rows.push(['Platform fee (paid by the carrier)', (Math.round((o.feePct || 0) * 10000) / 100) + '% = ' + money(feeCents)]);
    rows.push(['Carrier receives', money(rateCents - feeCents)]);
  }
  rows.push(['Detention', money(det.rateCentsPerHour) + ' per hour after ' + freeHours + ' free hour' + (freeHours === 1 ? '' : 's') + ' at a pickup or delivery stop']);
  rows.push(['Truck ordered, not used', money(o.tonuCents != null ? o.tonuCents : 25000) + ' to the carrier if the shipper cancels after the load is booked']);
  return { rateCents, feeCents, carrierReceivesCents: rateCents - feeCents, rows };
}

/** Who agreed, and when. Replaces blank signature lines nobody ever signed. */
function acceptanceRows(load, carrier, shipper) {
  const fp = load.acceptanceFingerprint || {};
  return [
    ['Shipper', joinParts((shipper && (shipper.companyName || shipper.name)) || 'N/A',
      'posted this load ' + (fmtDateTime(load.createdAt) || 'on the platform'),
      load.termsAcceptedAt ? 'accepted the posting terms ' + fmtDateTime(load.termsAcceptedAt) : null)],
    ['Carrier', joinParts(carrierDocIdentity(carrier).name,
      fp.at ? 'booked electronically ' + fmtDateTime(fp.at) + ' (signed-in account; device and network recorded)' : 'booked electronically on the platform')],
  ];
}

exports.documentContent = { bolSections, rateConTerms, acceptanceRows, hazmatDescription, pickupSignatures, fmtWindow };

function renderSections(doc, sections, y) {
  for (const s of sections) {
    if (!s.rows.length) continue;
    y = sectionTitle(doc, s.title, y);
    for (const [label, value] of s.rows) y = infoRow(doc, label, value, y);
    y += 6; drawHRule(doc, y); y += 10;
  }
  return y;
}

// ── Bill of Lading ───────────────────────────────────────────────────────────

exports.generateBOL = (load, carrier, shipper) => {
  return new Promise((resolve, reject) => {
    const fileName = load._id + '-bol.pdf';
    const filePath = path.join(UPLOADS_DIR, fileName);

    const doc = new PDFDocument({ size: 'LETTER', margins: { top: 100, bottom: 60, left: 50, right: 50 } });
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);

    addHeader(doc, 'BILL OF LADING', 'BOL #' + String(load._id).slice(-8).toUpperCase());

    let y = renderSections(doc, bolSections(load, carrier, shipper), 110);

    // Terms
    if (y > doc.page.height - 130) { doc.addPage(); y = 60; }
    doc.fontSize(8.5).fillColor('#64748b').font('Helvetica')
      .text(
        'Received, subject to the terms agreed between shipper and carrier, the freight described above in apparent good ' +
        'order, except as noted. Contents and condition of contents of packages are unknown to the carrier. Where the driver ' +
        'did not count the pieces, the count is the shipper\'s (shipper\'s load and count).',
        50, y, { width: 512, lineGap: 3 }
      );
    y += 50;

    // Signatures: shipper and driver at pickup, consignee at delivery. A captured e-signature is
    // drawn in; an empty slot stays a ruled line for a pen.
    if (y > doc.page.height - 290) { doc.addPage(); y = 60; }
    y = sectionTitle(doc, 'SIGNATURES', y) + 20;
    const at = pickupSignatures(load);
    drawSignature(doc, at.shipper, 'Shipper Signature:', 50, y, 300);
    drawSignature(doc, at.driver, 'Driver Signature:', 320, y, 562);
    drawSignature(doc, load.deliverySignature, 'Consignee Signature:', 50, y + 110, 300);

    addFooter(doc);
    doc.end();
    stream.on('finish', () => resolve('/documents/uploads/' + fileName));
    stream.on('error', reject);
  });
};

// ── Driver Settlement Statement ──────────────────────────────────────────────
// All settlement money is stored in integer cents; fmtMoney takes dollars, so
// divide by 100 at the boundary.

exports.generateSettlementStatement = (settlement, driver, company) => {
  return new Promise((resolve, reject) => {
    const fileName = settlement._id + '-settlement.pdf';
    const filePath = path.join(UPLOADS_DIR, fileName);

    const doc = new PDFDocument({ size: 'LETTER', margins: { top: 100, bottom: 60, left: 50, right: 50 } });
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);

    addHeader(doc, 'DRIVER SETTLEMENT', settlement.settlementNumber || String(settlement._id).slice(-8).toUpperCase());

    let y = 110;

    // Parties
    y = sectionTitle(doc, 'PARTIES', y);
    y = infoRow(doc, 'Carrier (Company)', carrierDocIdentity(company).name, y);
    y = infoRow(doc, 'MC Number', carrierDocIdentity(company).mcNumber, y);
    y = infoRow(doc, 'Driver', (driver && driver.name) || settlement.driverName || 'N/A', y);
    y = infoRow(doc, 'Statement #', settlement.settlementNumber || String(settlement._id), y);
    y += 8; drawHRule(doc, y); y += 12;

    // Period
    y = sectionTitle(doc, 'PAY PERIOD', y);
    y = infoRow(doc, 'Period Start', fmtDate(settlement.periodStart), y);
    y = infoRow(doc, 'Period End', fmtDate(settlement.periodEnd), y);
    y = infoRow(doc, 'Pay Type', settlement.payType || 'N/A', y);
    y += 8; drawHRule(doc, y); y += 12;

    // Line items
    y = sectionTitle(doc, 'LOADS & EARNINGS', y);
    doc.fontSize(8.5).fillColor('#64748b').font('Helvetica-Bold');
    doc.text('Load', 50, y, { width: 200 });
    doc.text('Delivered', 250, y, { width: 80 });
    doc.text('Revenue', 330, y, { width: 70, align: 'right' });
    doc.text('Deduct', 400, y, { width: 70, align: 'right' });
    doc.text('Net', 470, y, { width: 92, align: 'right' });
    doc.font('Helvetica').fillColor('#000000');
    y += 16;
    (settlement.lineItems || []).forEach((li) => {
      if (y > doc.page.height - 140) { doc.addPage(); y = 60; }
      doc.fontSize(8.5).fillColor('#1e293b');
      doc.text(String(li.loadTitle || li.loadId || 'Load'), 50, y, { width: 200 });
      doc.text(fmtDate(li.deliveredAt), 250, y, { width: 80 });
      doc.text(fmtMoney((li.loadRevenueCents || 0) / 100), 330, y, { width: 70, align: 'right' });
      doc.text(fmtMoney((li.deductionsCents || 0) / 100), 400, y, { width: 70, align: 'right' });
      doc.text(fmtMoney((li.netCents || 0) / 100), 470, y, { width: 92, align: 'right' });
      y += 15;
    });
    y += 6; drawHRule(doc, y); y += 12;

    // Totals
    y = sectionTitle(doc, 'SETTLEMENT TOTALS', y);
    y = infoRow(doc, 'Gross Earnings', fmtMoney((settlement.grossCents || 0) / 100), y);
    y = infoRow(doc, 'Total Deductions', fmtMoney((settlement.deductionsCents || 0) / 100), y);
    doc.rect(50, y, 512, 30).fillAndStroke('#f0fdf4', '#16a34a');
    doc.fontSize(12).fillColor('#15803d').font('Helvetica-Bold').text('NET PAY:', 66, y + 9);
    doc.fontSize(15).fillColor('#166534')
      .text(fmtMoney((settlement.netCents || 0) / 100), 350, y + 6, { align: 'right', width: 200 });
    doc.font('Helvetica').fillColor('#000000');

    addFooter(doc);
    doc.end();
    stream.on('finish', () => resolve('/documents/uploads/' + fileName));
    stream.on('error', reject);
  });
};

// ── Rate Confirmation ────────────────────────────────────────────────────────

exports.generateRateConfirmation = async (load, carrier, shipper) => {
  // The accessorial rates that really apply: the contract's when this is a contract load, else the platform defaults.
  const opts = {
    feePct: require('../config/fees').PLATFORM_FEE_PCT,
    paymentsOn: !!process.env.STRIPE_SECRET_KEY,
    detention: { freeMinutes: 120, rateCentsPerHour: 7500 },
    tonuCents: 25000,
  };
  if (load.contractId) {
    try {
      const c = await require('../models/Contract').findById(load.contractId).select('pricing.accessorialRates').lean();
      const r = c && c.pricing && c.pricing.accessorialRates;
      if (r) {
        opts.detention = { freeMinutes: (r.detentionFreeHours || 2) * 60, rateCentsPerHour: r.detentionPerHourCents || 7500 };
        if (r.tonuCents) opts.tonuCents = r.tonuCents;
      }
    } catch (_) { /* defaults stand */ }
  }
  const terms = rateConTerms(load, opts);

  return new Promise((resolve, reject) => {
    const fileName = load._id + '-ratecon.pdf';
    const filePath = path.join(UPLOADS_DIR, fileName);

    const doc = new PDFDocument({ size: 'LETTER', margins: { top: 100, bottom: 60, left: 50, right: 50 } });
    const stream = fs.createWriteStream(filePath);
    doc.pipe(stream);

    addHeader(doc, 'RATE CONFIRMATION', 'RC #' + String(load._id).slice(-8).toUpperCase());

    const id = carrierDocIdentity(carrier);
    const haz = hazmatDescription(load);
    let y = renderSections(doc, [
      { title: 'PARTIES', rows: [
        ['Shipper', (shipper && (shipper.companyName || shipper.name)) || 'N/A'],
        ['Shipper contact', (shipper && shipper.email) || 'N/A'],
        ['Carrier', id.name],
        ['Carrier contact', (carrier && carrier.email) || 'N/A'],
        ['MC number', id.mcNumber], ['DOT number', id.dotNumber],
      ] },
      { title: 'LOAD', rows: [
        ['Load reference', String(load._id)],
        ...referenceRows(load),
        ...freightRows(load),
        ['Hazardous material', haz ? haz + (load.hazmatEmergencyPhone ? ' · emergency ' + load.hazmatEmergencyPhone : '') : 'No'],
        ['Special instructions', load.specialInstructions],
        ['Instructions for the carrier', load.carrierInstructions],
      ].filter((r) => r[1]) },
      { title: 'PICKUP', rows: placeRows(load, 'pickup') },
      { title: 'DELIVERY', rows: placeRows(load, 'delivery') },
    ], 110);

    // Rate box
    if (y > doc.page.height - 200) { doc.addPage(); y = 60; }
    y = sectionTitle(doc, 'RATE & PAYMENT', y);
    doc.rect(50, y, 512, 36).fillAndStroke('#f0fdf4', '#16a34a');
    doc.fontSize(13).fillColor('#15803d').font('Helvetica-Bold')
      .text('Total Agreed Rate:', 66, y + 10);
    doc.fontSize(16).fillColor('#166534')
      .text(fmtMoney(terms.rateCents / 100), 350, y + 7, { align: 'right', width: 200 });
    doc.font('Helvetica').fillColor('#000000');
    y += 48;
    for (const [label, value] of terms.rows) y = infoRow(doc, label, value, y);
    y += 6; drawHRule(doc, y); y += 10;

    // Terms
    if (y > doc.page.height - 170) { doc.addPage(); y = 60; }
    y = sectionTitle(doc, 'TERMS', y);
    doc.fontSize(8.5).fillColor('#64748b').font('Helvetica')
      .text(
        '1. The carrier agrees to transport the freight described from pickup to delivery at the agreed rate.\n' +
        '2. The carrier shall comply with all applicable federal and state regulations.\n' +
        '3. Detention and cancellation charges are as stated above.\n' +
        '4. Claims for loss or damage must be filed in writing within 9 months of delivery.\n' +
        '5. This confirmation was agreed electronically on the FreightConnect platform; the record of who agreed and when is below.',
        50, y, { width: 512, lineGap: 4 }
      );
    y += 84;

    y = renderSections(doc, [{ title: 'ACCEPTANCE RECORD', rows: acceptanceRows(load, carrier, shipper) }], y);

    addFooter(doc);
    doc.end();
    stream.on('finish', () => resolve('/documents/uploads/' + fileName));
    stream.on('error', reject);
  });
};
